"""Rendered fetching -- runs the page's JavaScript and measures where its text landed.

This module exists for two reasons, and the second is the important one:

1. Client-rendered pages have no content in their static HTML.
2. **Reading order needs geometry.** Source order is not visual order (MEMORY.md D10), and
   the only way to know where text actually sits is to lay the page out and measure it.

Binding measurements back to parsed elements
--------------------------------------------
Rects are collected in the browser but consumed by lxml, so the two need a shared key.
Recomputing an XPath in JavaScript to match lxml's `getpath()` output is fragile -- the
formats differ over when an index is emitted, and a mismatch fails silently by yielding no
geometry at all.

Instead the browser stamps every element with a marker attribute (`MARKER_ATTRIBUTE` in
`webgraph.markers`) *before* serialising the DOM. The attribute survives into the HTML we
parse, so each element can be found again and keyed by whatever path lxml itself produces.
The key is generated by the same library that consumes it, which removes the mismatch
entirely.

The browser-side programs live as plain JavaScript in `fetch/js/` -- `reveal.js`,
`gate_probe.js`, `collect.js` -- and receive the attribute names as their one argument, so
the contract between the two runtimes is written down exactly once, in `webgraph.markers`.
"""

