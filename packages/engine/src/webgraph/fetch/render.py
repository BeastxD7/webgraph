@cache

@dataclass(frozen=True, slots=True)
class RenderConfig:
    timeout_ms: int = config.RENDER_TIMEOUT_MS
    wait_until: Literal["commit", "domcontentloaded", "load", "networkidle"] = config.RENDER_WAIT_UNTIL  # type: ignore[assignment]
    """`load`, not `networkidle`.

    `networkidle` waits for 500ms of no network activity, which **never happens** on sites
    with analytics beacons, polling, websockets or video preloading. Measured against 24 real
    sites it timed out on 5 of them (21%) -- Shopify, Squarespace, Stripe, python.org and
    Figma -- losing those pages entirely. `load` plus an explicit settle is slightly earlier
    but actually fires."""

    viewport_width: int = config.RENDER_VIEWPORT_WIDTH
    viewport_height: int = config.RENDER_VIEWPORT_HEIGHT
    """Width matters for reading order -- a narrow viewport collapses a multi-column layout
    into one column, which changes the correct answer."""

    settle_ms: int = config.RENDER_SETTLE_MS
    """Pause after load to let hydration and layout settle before measuring.

    Carries the weight that `networkidle` used to: most client-side frameworks finish
    hydrating within a few hundred milliseconds of `load`, and measuring before that captures
    the pre-hydration layout."""

    dismiss_gates: bool = config.RENDER_DISMISS_GATES
    """Open a first-run interstitial that is blocking the page from mounting.

    On by default, on the same asymmetric-cost reasoning that biases `_needs_render` toward
    rendering: a gate left closed loses essentially the whole site -- 97% of the text and
    *every* internal link on the measured case -- while a wrongly-suspected gate costs one
    guarded click and is discarded unless it measurably improves the page.

    This is the one place the engine clicks anything, and `fetch/js/reveal.js`'s reasons for
    refusing to click still stand, so the click is fenced in four ways: it only happens on a
    page that has almost no text *and* almost no internal links; candidates inside a `<form>`
    or carrying a real `href` are never chosen; labels reading as a transaction, refusal or
    sign-out are excluded; and the result is thrown away unless the page gets decisively
    better. A click that navigates off-origin is reverted.
    """

    reveal_collapsed: bool = config.RENDER_REVEAL_COLLAPSED
    """Open `<details>` and ARIA disclosure panels before measuring.

    Reaches content the page hides until someone interacts, without clicking anything -- see
    `fetch/js/reveal.js` for why clicking is the wrong tool. Off until measured; see MEMORY.md.
    """

    user_agent: str | None = None
    headless: bool = config.RENDER_HEADLESS
    reuse_browser: bool = config.RENDER_REUSE_BROWSER
    """Reuse the calling thread's browser rather than launching one per page.

    Launch is a fixed cost per page -- see `fetch/browser.py` for why the reuse is
    thread-local. Disable it to isolate a page that crashes the browser."""

    block_resources: tuple[str, ...] = config.RENDER_BLOCK_RESOURCES
    """Skipped to cut bandwidth and time. Fonts are blocked deliberately: metrics shift
    slightly without them, but not enough to change column structure."""

def _script(name: str) -> str:
    """Browser-side program `fetch/js/<name>.js`, read once per process.

    Each file is an arrow function `(markers) => { ... }`; pass `marker_arguments()` as the
    argument to `page.evaluate` so the script never spells out an attribute name itself.
    """
    return (files("webgraph.fetch") / "js" / f"{name}.js").read_text(encoding="utf-8")


@dataclass(frozen=True, slots=True)
class RenderResult:
    url: str
    """The address the browser ended on, after redirects. Relative links resolve against
    this, and a crawl's scope is judged against its host."""

    html: str
    """Serialised *after* marker attributes were stamped, so the markers are present."""

    rects: dict[str, Rect]
    """Keyed by marker id, not XPath. Use `geometry_by_xpath` to rekey for the pipeline."""

    ok: bool
    error: str | None = None
    status: int | None = None
    """The HTTP status of the document the browser landed on, None when the navigation
    produced no response (a timeout salvaged from what the page already had). `ok` says
    the browser navigated and measured; it does not say the server answered with a page --
    flipkart.com answered Chromium 503 "No server is available" while the plain fetch got
    the listing, and `resolve_page` needs the number to tell the two apart."""
    globals: dict[str, str] = field(default_factory=dict)
    """Library versions read from live JavaScript globals -- the only place most of them
    appear. `jquery.min.js` has no version in its filename; `jQuery.fn.jquery` has it exactly."""

    custom_globals: tuple[str, ...] = ()
    """Every global the page added, diffed against a pristine window.

    Hand-written probes only find what someone thought to name. This finds the rest --
    `Tinybird`, `__reactRouterVersion`, `lenisVersion` -- and is what closes most of the gap
    with a browser extension that can read the live heap."""

    requests: tuple[str, ...] = ()
    """Every URL the page requested while loading.

    A third-party service is frequently invisible in the markup and unmistakable in the
    network log: PostHog arrives as `us-assets.i.posthog.com/array/.../config.js`, and
    Cloudflare's bot management as a `/cdn-cgi/challenge-platform/` script."""

    cookies: dict[str, str] = field(default_factory=dict)
    """Cookies present after load, from the browser jar rather than the document's own
    `Set-Cookie`. Cookies set by a third-party script never appear in the main response."""

    scripts: tuple[str, ...] = ()
    """`src` of every script element after hydration, including ones injected at runtime."""

    links: tuple[str, ...] = ()
    """`rel href` of every link element, for manifest, preconnect and stylesheet signals."""

    shadow_roots: int = 0
    """Open shadow roots pierced while measuring. Recorded because their content is invisible
    to every DOM-based extractor that does not go looking for it, so a caller comparing
    against another tool should know when this page had any."""

    gate_dismissed: bool = False
    """True when an interstitial was opened to reach the page. Recorded rather than silent:
    the caller is entitled to know the measured page required a click to exist."""

    gate_note: str | None = None

    navigation_note: str | None = None
    """Set when navigation timed out and the document was read as it stood. The render is
    still `ok`: a page whose adverts never finished loading is a page, and reporting it as a
    failure loses it over something that was never the content."""
    """What was observed, when a gate was suspected -- whether or not it opened."""


def _open_gate(page: Any) -> tuple[bool, str | None]:
    """Try to open a first-run interstitial that is stopping the page from mounting.

    Returns (whether the page was opened, what was observed). Never raises: a page that
    cannot be probed is simply not a page with a gate we can open, and a failed click must
    not cost the caller the render it already has.

    The accept test is the whole safety argument. A click is kept only when the page gets
    decisively better on *both* axes the probe (`fetch/js/gate_probe.js`) measures -- text and internal links -- so a
    click that opened a tooltip, dismissed a cookie bar or did nothing at all leaves the
    result unchanged rather than being reported as a success.
    """
    try:
        before = page.evaluate(_script("gate_probe"), marker_arguments())
    except Exception:
        return False, None

    text_before = int(before.get("textLength") or 0)
    links_before = int(before.get("internalLinks") or 0)
    candidates = list(before.get("candidates") or ())

    if text_before > GATE_MAX_TEXT or links_before > GATE_MAX_LINKS:
        return False, None
    if not candidates:
        return False, (
            f"page looks gated ({text_before} chars, {links_before} internal links) "
            "but no control was found to open it"
        )

    origin_before = urlsplit(page.url)

    for marker in candidates:
        try:
            page.click(f"[{GATE_ATTRIBUTE}='{marker}']", timeout=2_000, no_wait_after=True)
        except Exception:
            continue

        try:
            page.wait_for_timeout(600)
            after = page.evaluate(_script("gate_probe"), marker_arguments())
        except Exception:
            continue

        # A click that left the origin followed a link rather than opening a gate. Go back
        # and treat it as a failed candidate; the guard would refuse the new address anyway.
        landed = urlsplit(page.url)
        if landed.netloc != origin_before.netloc:
            try:
                page.go_back(timeout=5_000)
                page.wait_for_timeout(400)
            except Exception:
                pass
            continue

        text_after = int(after.get("textLength") or 0)
        links_after = int(after.get("internalLinks") or 0)

        opened = (
            text_after >= max(text_before * GATE_MIN_GAIN, text_before + 200)
            and links_after > links_before
        )
        if opened:
            return True, (
                f"opened an interstitial: {text_before} -> {text_after} chars, "
                f"{links_before} -> {links_after} internal links"
            )

    return False, (
        f"page looks gated ({text_before} chars, {links_before} internal links); "
        f"{len(candidates)} control(s) tried, none opened it"
    )


class RenderDiagnosisError(Exception):
    """A failure this module diagnosed itself, reported as a sentence rather than a trace.

    The outer handler prints other exceptions with their class name, because for an
    unexpected failure the class is the best clue there is. For one of these the class is
    ours and the message already says what happened."""


class NavigationNeverStartedError(RenderDiagnosisError):
    """The server sent nothing before the timeout; the page never left `about:blank`."""


class DownloadedInsteadOfPageError(RenderDiagnosisError):
    """The address served a file, not a document.

    Its own type rather than a string match at the call site: a caller deciding whether to
    retry, escalate or give up needs to tell "this is not a web page" from "the browser
    broke", and those want opposite responses."""


def _is_download(exc: Exception) -> bool:
    """Whether Playwright refused a navigation because it became a download."""
    return "download is starting" in str(exc).lower()


def _looks_empty(html: str) -> bool:
    """Whether a salvaged document is a page or an error wearing one's clothes."""
    body = re.sub(r"<[^>]+>", " ", html)
    return len(re.sub(r"\s+", " ", body).strip()) < MIN_SALVAGED_TEXT


def _timeout_note(exc: Exception, config: RenderConfig) -> str:
    """One line saying what timed out, for the result rather than for a log nobody reads."""
    return (
        f"navigation timed out after {config.timeout_ms} ms waiting for "
        f"'{config.wait_until}'; read the document as it stood ({type(exc).__name__})"
    )


def render_page(url: str, *, config: RenderConfig | None = None) -> RenderResult:
    """Load `url` in a headless browser and measure every visible element."""
    if not PLAYWRIGHT_AVAILABLE:
        return RenderResult(
            url=url,
            html="",
            rects={},
            ok=False,
            error="playwright is not installed; install the 'render' extra",
        )

    try:
        guard.check_url(url)
    except guard.BlockedHostError as exc:
        return RenderResult(url=url, html="", rects={}, ok=False, error=str(exc))

    config = config or RenderConfig()

    def _measure(browser: Any) -> dict[str, Any]:
        """One page, in its own context so nothing leaks between pages of a crawl."""
        context = browser.new_context(
            viewport={"width": config.viewport_width, "height": config.viewport_height},
            user_agent=config.user_agent,
        )
        try:
            page = context.new_page()

            # The network log is a first-class fingerprinting signal, not diagnostics: a
            # third-party service is often invisible in the markup and unmistakable here.
            # Capped, because an image-heavy page can issue hundreds of requests and only
            # the distinct hosts and paths carry information.
            requests: list[str] = []

            def _record(request: Any) -> None:
                if len(requests) < MAX_RECORDED_REQUESTS:
                    requests.append(str(request.url))

            page.on("request", _record)

            if config.block_resources:
                blocked = set(config.block_resources)
                page.route(
                    "**/*",
                    lambda route: (
                        route.abort()
                        if route.request.resource_type in blocked
                        else route.continue_()
                    ),
                )

            navigation_note: str | None = None
            try:
                response = page.goto(
                    url, timeout=config.timeout_ms, wait_until=config.wait_until
                )
            except PlaywrightTimeoutError as exc:
                # A navigation timeout is not an empty page. `wait_until="load"` waits for
                # every image, advert and tracker a commercial page pulls in, and on an
                # ad-heavy retail site that event may never fire -- while the document
                # itself finished long before. Discarding what the browser already has
                # because a third-party pixel is slow throws away the page over something
                # that was never the page.
                #
                # So the timeout is recorded and the content is read anyway. If the
                # document really is empty, the emptiness checks below catch it on its own
                # merits rather than on the timeout's say-so.
                response = None
                navigation_note = _timeout_note(exc, config)
            except Exception as exc:
                if not _is_download(exc):
                    raise
                # The navigation produced a file, not a page. There is nothing to render and
                # nothing to wait for, so the browser's own message ("Download is starting")
                # is reported as what it means instead of surfacing a driver error. Seen on
                # amazon.in, which answers some requests with an attachment.
                raise DownloadedInsteadOfPageError(
                    "the server returned a file download rather than a page"
                ) from exc
            # The browser follows redirects itself, so the address that was checked above
            # is not necessarily the one that answered. Raising here is caught by the
            # handler at the bottom and reported as a failed render.
            if response is not None:
                guard.check_url(str(response.url))
            elif navigation_note is not None:
                # The address may have moved before the timeout; re-check what we landed on.
                # Unless it never left: a navigation that timed out before the server sent a
                # first byte leaves the page on `about:blank`, and checking *that* against
                # the host policy reported a genuine timeout as "refusing non-HTTP scheme:
                # about" -- a security refusal that never happened. Seen on every
                # reliancedigital.in brand page, whose edge takes 30 s to answer 504.
                if page.url.startswith("about:"):
                    raise NavigationNeverStartedError(
                        f"the server sent nothing within {config.timeout_ms / 1000:.0f}s; "
                        "the navigation never started"
                    )
                guard.check_url(page.url)
            if config.settle_ms:
                page.wait_for_timeout(config.settle_ms)

            if config.reveal_collapsed:
                try:
                    revealed = int(page.evaluate(_script("reveal"), marker_arguments()) or 0)
                except Exception:
                    revealed = 0
                if revealed:
                    # Let layout settle: opening a panel reflows everything below it, and
                    # reading order is measured from geometry.
                    page.wait_for_timeout(250)

            gate_dismissed = False
            gate_note: str | None = None
            if config.dismiss_gates:
                gate_dismissed, gate_note = _open_gate(page)
                if gate_dismissed:
                    # Mounting the real page reflows everything, and reading order is
                    # measured from geometry.
                    page.wait_for_timeout(config.settle_ms or 500)

            payload = dict(page.evaluate(_script("collect"), marker_arguments()))
            # The address the browser *landed on*, not the one it was given. A short link
            # (amzn.in/d/...) redirects to the real host, and every relative link on the page
            # resolves against the real host. Reporting the requested address resolved them
            # all against the short-link domain, the crawl's scope rejected every one as
            # off-site, and a whole-site crawl of Amazon discovered exactly one page.
            payload["landed_url"] = page.url if page.url.startswith(("http://", "https://")) else url
            payload["status"] = response.status if response is not None else None
            payload["gate_dismissed"] = gate_dismissed
            payload["gate_note"] = gate_note
            payload["navigation_note"] = navigation_note
            payload["requests"] = requests
            # From the jar, not from the document's own `Set-Cookie`: a cookie written by a
            # third-party script never appears in the main response headers.
            payload["cookies"] = {
                str(cookie.get("name", "")): str(cookie.get("value", ""))
                for cookie in context.cookies()
            }
            return payload
        finally:
            context.close()

    try:
        shared = shared_browser(headless=config.headless) if config.reuse_browser else None
        if shared is not None:
            payload: dict[str, Any] = _measure(shared)
        else:
            # No slot free, reuse disabled, or the shared launch failed: fall back to a
            # private browser so a render never depends on the pool being available.
            with sync_playwright() as driver:
                browser = driver.chromium.launch(
                    headless=config.headless, args=list(browser_module.LAUNCH_ARGS)
                )
                try:
                    payload = _measure(browser)
                finally:
                    browser.close()

        # A salvaged timeout is only worth keeping if something was salvaged. Measured on
        # reliancedigital.in, whose server answers a 288-character document whose entire body
        # is the words "stream timeout": without this the salvage turns that failure into a
        # success carrying somebody else's error message as the page.
        salvaged_html = str(payload["html"])
        if payload.get("navigation_note") and _looks_empty(salvaged_html):
            return RenderResult(
                url=url,
                html="",
                rects={},
                ok=False,
                error=str(payload["navigation_note"]),
            )

        rects = {
            key: Rect(
                x=float(value["x"]),
                y=float(value["y"]),
                width=float(value["width"]),
                height=float(value["height"]),
            )
            for key, value in payload["rects"].items()
        }
        raw_globals = payload.get("globals") or {}
        return RenderResult(
            url=str(payload.get("landed_url") or url),
            html=salvaged_html,
            rects=rects,
            ok=True,
            status=int(payload["status"]) if payload.get("status") is not None else None,
            globals={str(k): str(v) for k, v in raw_globals.items()},
            custom_globals=tuple(str(name) for name in payload.get("customGlobals") or ()),
            requests=tuple(str(item) for item in payload.get("requests") or ()),
            cookies={str(k): str(v) for k, v in (payload.get("cookies") or {}).items()},
            scripts=tuple(str(item) for item in payload.get("scripts") or ()),
            links=tuple(str(item) for item in payload.get("links") or ()),
            shadow_roots=int(payload.get("shadowRoots") or 0),
            gate_dismissed=bool(payload.get("gate_dismissed")),
            gate_note=payload.get("gate_note") or None,
            navigation_note=payload.get("navigation_note") or None,
        )

    except RenderDiagnosisError as exc:
        # Our own diagnosis, so it is reported as a sentence rather than decorated with a
        # class name the reader has no use for.
        return RenderResult(url=url, html="", rects={}, ok=False, error=str(exc))

    except Exception as exc:
        return RenderResult(
            url=url, html="", rects={}, ok=False, error=f"{type(exc).__name__}: {exc}"
        )


@dataclass(frozen=True, slots=True)
class HiddenMatter:
    """What the browser laid out and hid, in the form `resolve._key` gives a block."""

    lines: frozenset[str]
    """Each hidden element's whole text, and each text node inside it: a menu item is
    matched exactly, however short."""

    text: str
    """The hidden elements' text joined, for a block that spans several nodes."""

    largest: int = 0
    """Characters of the single largest hidden element (outermost: an element inside
    another hidden one is counted in its ancestor). One element that hides more than the
    page shows is a gate over the page -- a country picker, a consent dialog with the
    body set `display: none` behind it -- where many small ones are menus and collapsed
    sections; `resolve.union_documents` tells the two apart by this."""

    def holds(self, key: str, *, min_chars: int) -> bool:
        return key in self.lines or (len(key) >= min_chars and key in self.text)


def hidden_matter(html: str) -> HiddenMatter:
    """Every word the browser laid out as `display: none` or `visibility: hidden`.

    The union of the static and rendered documents keeps a block only the static one has,
    on the reasoning that the render lost it (a consent wall, a lazy section). A block the
    renderer *hid* is not lost: the browser saw it and judged it. php.net's manual TOC
    (`nav#trick`, ~100 links, `display: none`) and cppreference's hover menus were dropped
    from the rendered document and put straight back by the union from the static one.
    `union_documents` checks a static-only block against this.

    Only the kinds a reader cannot see: `display`, `visibility` and `offscreen` (a box
    entirely at negative page coordinates -- vtu.ac.in's injected links, which the static
    fetch holds without any marker and the union must not put back). Clipped
    (screen-reader-only) text is the `include_hidden_text` option's business, and a
    collapsed `overflow` tray is in the flow of the page.
    """
    from webgraph.dom.blocks import parse_html
    from webgraph.markers import HIDDEN_ATTRIBUTE

    root = parse_html(html)
    lines: set[str] = set()
    wholes: list[str] = []
    largest = 0
    hidden_kinds = ("display", "visibility", "offscreen")
    for element in root.xpath(
        f"//*[@{HIDDEN_ATTRIBUTE}='display' or @{HIDDEN_ATTRIBUTE}='visibility'"
        f" or @{HIDDEN_ATTRIBUTE}='offscreen']"
    ):
        whole = "".join(element.text_content().split()).casefold()
        if not whole:
            continue
        wholes.append(whole)
        lines.add(whole)
        for text in element.itertext():
            key = "".join(text.split()).casefold()
            if key:
                lines.add(key)
        # Outermost only: a hidden element inside a hidden element is its ancestor's.
        if not any(a.get(HIDDEN_ATTRIBUTE) in hidden_kinds for a in element.iterancestors()):
            largest = max(largest, len(whole))
    return HiddenMatter(frozenset(lines), "\n".join(wholes), largest)


def geometry_by_xpath(html: str, rects: dict[str, Rect]) -> dict[str, Rect]:
    """Rekey browser measurements from marker ids to lxml XPaths.

    Parsing here rather than in the caller keeps the marker convention private to this
    module, and guarantees the XPath is produced by the same lxml version that will later
    consume it.
    """
    from webgraph.dom.blocks import parse_html

    root = parse_html(html)
    tree = root.getroottree()
    geometry: dict[str, Rect] = {}

    for element in root.xpath(f"//*[@{MARKER_ATTRIBUTE}]"):
        marker = element.get(MARKER_ATTRIBUTE)
        if marker is not None and marker in rects:
            geometry[tree.getpath(element)] = rects[marker]

    return geometry
